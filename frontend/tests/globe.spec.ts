test('supports dragging, returns north up on release and keeps keyboard rotation available while paused', async ({ page }) => {
  await page.goto('/')
  const globe = page.locator('.hero-earth')
  await expect(globe).toHaveAttribute('data-globe-state', 'ready')
  await expect(globe).toHaveAttribute('data-cambodia-outline', 'true')
  await expect(page.locator('.hero-country-target')).toHaveCount(0)
  await page.getByRole('button', { name: 'Pause globe and backgrounds' }).click()
  const canvas = page.getByRole('img', { name: /^Rotate Earth/ })
  const bounds = await canvas.boundingBox()
  if (!bounds) throw new Error('Globe is missing')
  const original = await globe.getAttribute('data-orientation')
  await page.mouse.move(bounds.x + bounds.width * .55, bounds.y + bounds.height * .45)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .7, bounds.y + bounds.height * .63, { steps: 8 })
  await expect(canvas).toHaveClass(/is-dragging/)
  await expect(globe).not.toHaveAttribute('data-orientation', original!)
  await expect.poll(async () => Math.abs(Number(await globe.getAttribute('data-north-tilt')))).toBeGreaterThan(.2)
  await page.mouse.up()
  await expect(canvas).not.toHaveClass(/is-dragging/)
  await expect(globe).toHaveAttribute('data-north-tilt', '0')
  const rotated = await globe.getAttribute('data-orientation')
  expect(rotated).not.toBe(original)
  await canvas.focus()
  await page.keyboard.down('ArrowUp')
  await expect(globe).not.toHaveAttribute('data-north-tilt', '0')
  await page.keyboard.up('ArrowUp')
  await expect(globe).toHaveAttribute('data-north-tilt', '0')
  await page.getByRole('button', { name: 'Reset globe north up' }).click()
  await expect(globe).toHaveAttribute('data-north-tilt', '0')
})


