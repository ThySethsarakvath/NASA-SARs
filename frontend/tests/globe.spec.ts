import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('rotates the real Earth texture, changes context photographs and pauses both', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  const globe = page.locator('.hero-earth')
  await expect(globe).toHaveAttribute('data-globe-state', 'ready')
  const orientation = await globe.getAttribute('data-orientation')
  await expect.poll(() => globe.getAttribute('data-orientation')).not.toBe(orientation)
  await expect(page.locator('.landing-hero')).not.toHaveAttribute('data-background-theme', '01', { timeout: 10000 })
  await page.getByRole('button', { name: 'Pause globe and backgrounds' }).click()
  await expect(globe).toHaveAttribute('data-motion', 'paused')
  const paused = await globe.getAttribute('data-orientation')
  // Allow several render intervals to pass: a paused globe must remain fixed.
  await page.waitForTimeout(300)
  expect(await globe.getAttribute('data-orientation')).toBe(paused)
  mkdirSync('output/playwright', { recursive: true })
  await page.screenshot({ path: 'output/playwright/globe-hero.png' })
  await page.getByRole('button', { name: 'Resume globe and backgrounds' }).click()
  await expect.poll(() => globe.getAttribute('data-orientation')).not.toBe(paused)
  expect(errors).toEqual([])
})

test('turns toward Cambodia and hands off to a prepared flood map', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.hero-earth')).toHaveAttribute('data-globe-state', 'ready')
  await page.getByRole('link', { name: 'Explore the flood prototype', exact: true }).click()
  await expect(page.locator('.hero-earth')).toHaveAttribute('data-globe-state', 'focusing')
  await expect(page.locator('.experience-root')).toHaveAttribute('data-handoff', 'preparing')
  await expect(page.locator('.hero-launch-status')).toContainText('Locating Cambodia')
  await expect(page.locator('.hero-country-label')).toContainText('CAMBODIA')
  const stage = page.locator('.hero-globe-stage.is-flying')
  await expect(page.locator('.hero-earth')).toHaveAttribute('data-flight-phase', 'zooming')
  await expect.poll(async () => Math.round((await stage.boundingBox())?.width ?? 0)).toBe(1440)
  const bounds = await stage.boundingBox()
  expect(bounds?.x).toBe(0)
  expect(bounds?.y).toBe(0)
  expect(bounds?.height).toBe(900)
  await expect.poll(async () => Number(await page.locator('.hero-earth').getAttribute('data-camera-distance'))).toBeLessThan(1.6)
  await page.screenshot({ path: 'output/playwright/cambodia-transition.png' })
  await expect(page).toHaveURL(/page=explore/)
  await expect(page.locator('.experience-root')).toHaveAttribute('data-handoff', 'explorer', { timeout: 10000 })
  await expect(page.getByText('Derived exports · source provenance and validation pending')).toBeVisible()
  await expect(page.getByRole('button', { name: 'After', exact: true })).toBeEnabled()
  await expect(page.locator('.hero-flight-veil, .hero-globe-stage.is-flying')).toHaveCount(0)
  await expect(page.locator('.explorer-layer main')).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
})

