import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('uses low/high comparison, combined imagery and date-matched baseline exposure', async ({ page }) => {
  const requests: string[] = []
  page.on('request', (request) => requests.push(request.url()))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?page=explore&case=tonle-sap-2026')
  await expect(page.locator('.map-workspace')).toHaveAttribute('data-map-state', 'ready')
  await expect(page.locator('[data-metric="areaKm2"] strong')).toContainText('7,348.6')
  await page.getByRole('button', { name: 'Before', exact: true }).click()
  await expect(page.locator('[data-metric="areaKm2"] strong')).toContainText('3,194.4')
  await page.locator('.prepared-controls summary').click()
  await page.getByRole('button', { name: 'Compare low / high water' }).click()
  await expect(page).toHaveURL(/from=2026-07-01/)
  await expect(page).toHaveURL(/to=2026-10-05/)
  await expect(page).toHaveURL(/display=both/)
  await expect(page.locator('.map-workspace')).toHaveAttribute('data-map-state', 'ready')
  await expect(page.locator('[data-metric="areaKm2"] strong')).toContainText('10,003.3')
  await expect(page.getByRole('slider', { name: 'Comparison divider position' })).toHaveValue('50')
  expect(requests.some((url) => url.endsWith('/sar_20260701.png'))).toBe(true)
  expect(requests.some((url) => url.endsWith('/water_20261005.png'))).toBe(true)
  await page.getByRole('checkbox', { name: 'Baseline-filtered open water', exact: true }).check()
  await expect(page).toHaveURL(/baseline=rare-water/)
  await expect(page.locator('[data-metric="areaKm2"] strong')).toContainText('1,463.2')
  await expect(page.locator('.control-deck')).toContainText('Baseline-filtered open water')
  await expect(page.getByRole('switch')).toBeDisabled()
  await page.reload()
  await expect(page.locator('[data-metric="areaKm2"] strong')).toContainText('1,463.2')
  await page.getByRole('button', { name: 'Before', exact: true }).click()
  await expect(page.locator('[data-metric="areaKm2"] strong')).toContainText('436.6')
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  mkdirSync('output/playwright', { recursive: true })
  await page.screenshot({ path: 'output/playwright/updated-exposure-desktop.png', animations: 'disabled' })
})

test('hides date-specific estimates for season maps and remains usable on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?page=explore&case=tonle-sap-2026&display=both&baseline=rare-water')
  await expect(page.getByRole('button', { name: 'After', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Open evidence panel' }).click()
  await expect(page.locator('[data-metric="areaKm2"] strong')).toContainText('502')
  await expect(page.locator('[data-metric="areaKm2"] strong')).toBeVisible()
  await page.screenshot({ path: 'output/playwright/updated-exposure-mobile.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Close evidence panel' }).click()
  await page.locator('.prepared-controls summary').click()
  await page.getByLabel('Data layer', { exact: true }).selectOption('frequency')
  await page.locator('.prepared-controls summary').click()
  await page.getByRole('button', { name: 'Open evidence panel' }).click()
  await expect(page.locator('.exposure-summary')).toContainText('Choose a dated view')
  await expect(page.locator('.exposure-metric')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('reports an unavailable proxy or required radar background without substituting another display', async ({ page }) => {
  await page.route('**/unusual_20261029.png', (route) => route.fulfill({ status: 404 }))
  await page.goto('/?page=explore&case=tonle-sap-2026&baseline=rare-water')
  await expect(page.getByText('Observation image unavailable. Comparison is disabled.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'After', exact: true })).toBeDisabled()
  await page.unroute('**/unusual_20261029.png')
  await page.route('**/sar_20261029.png', (route) => route.fulfill({ status: 404 }))
  await page.goto('/?page=explore&case=tonle-sap-2026&display=both')
  await expect(page.getByText('Observation image unavailable. Comparison is disabled.')).toBeVisible()
})
